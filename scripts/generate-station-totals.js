#!/usr/bin/env node
/**
 * Regenerates src/lib/stationTotals.ts based on feature counts
 * for every city under src/app/(game)/** that has data/features.json.
 */
const fs = require('fs')
const path = require('path')

const gameDir = path.join(__dirname, '..', 'src', 'app', '(game)')
const outFile = path.join(__dirname, '..', 'src', 'lib', 'stationTotals.ts')
const miniCityRegistryPath = path.join(
  __dirname,
  '..',
  'src',
  'lib',
  'miniCitiesRegistry.json',
)

const totals = {}
const featureCollectionsByCity = {}

const registerFeatureCollection = (citySlug, json, priority) => {
  const existing = featureCollectionsByCity[citySlug]
  if (existing && existing.__priority > priority) {
    return
  }

  featureCollectionsByCity[citySlug] = {
    ...json,
    __priority: priority,
  }
  totals[citySlug] = json.features.length
}

const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const entryPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      walk(entryPath)
      continue
    }
    if (entry.isFile() && entry.name === 'features.json') {
      const parent = path.basename(dir)
      const grandparent = path.basename(path.dirname(dir))
      const isPrimaryData = parent === 'data'
      const isFullData = parent === 'full' && grandparent === 'data'
      if (!isPrimaryData && !isFullData) continue

      const cityDir = isFullData
        ? path.basename(path.dirname(path.dirname(dir)))
        : path.basename(path.dirname(dir))
      const priority = isFullData ? 1 : 0

      try {
        const raw = fs.readFileSync(entryPath, 'utf-8')
        const json = JSON.parse(raw)
        if (json && Array.isArray(json.features)) {
          registerFeatureCollection(cityDir, json, priority)
        }
      } catch (err) {
        console.warn(`Skipping ${cityDir}: ${err.message}`)
      }
    }
  }
}

walk(gameDir)

try {
  const registryRaw = fs.readFileSync(miniCityRegistryPath, 'utf-8')
  const registry = JSON.parse(registryRaw)
  const parents = Array.isArray(registry?.parents) ? registry.parents : []

  parents.forEach((parent) => {
    const parentSlug = parent?.parentSlug
    const parentFeatures = featureCollectionsByCity[parentSlug]
    const children = Array.isArray(parent?.children) ? parent.children : []
    if (!parentSlug || !parentFeatures || !Array.isArray(parentFeatures.features)) {
      return
    }

    children.forEach((child) => {
      const childSlug = child?.slug
      const includeLines = Array.isArray(child?.includeLines)
        ? child.includeLines
        : []
      if (!childSlug || includeLines.length === 0) {
        return
      }

      const lineSet = new Set(includeLines)
      totals[childSlug] = parentFeatures.features.filter((feature) =>
        lineSet.has(feature?.properties?.line),
      ).length
    })
  })
} catch (err) {
  console.warn(`Skipping mini-city totals: ${err.message}`)
}

const sorted = Object.keys(totals).sort()

const lines = []
lines.push('// Auto-generated by scripts/generate-station-totals.js')
lines.push('// Do not edit manually.')
lines.push('export const STATION_TOTALS: Record<string, number> = {')
for (const key of sorted) {
  lines.push(`  "${key}": ${totals[key]},`)
}
lines.push('}')
lines.push('')

fs.writeFileSync(outFile, lines.join('\n'))
console.log(`Wrote ${outFile} with ${sorted.length} cities.`)
